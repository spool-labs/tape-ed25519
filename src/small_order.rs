//! Key encodings that decode to a point of small order, which anyone can sign for

use crate::verifying_key::VERIFYING_KEY_LENGTH;

/// Byte that holds the sign of x in an encoding
const SIGN_BYTE: usize = VERIFYING_KEY_LENGTH - 1;

/// Bit of the sign byte that holds the sign of x
const SIGN_BIT: u8 = 0x80;

/// Every y encoding of the eight small-order points, canonical and non-canonical, sign bit clear
