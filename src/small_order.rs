/// Whether a key encoding decodes to a small-order point, such as the all-zero system program address
pub fn is_small_order_encoding(encoded: &[u8; VERIFYING_KEY_LENGTH]) -> bool {
    let mut y = *encoded;
    y[SIGN_BYTE] &= !SIGN_BIT;
    for candidate in &SMALL_ORDER_Y {
        if y == *candidate {
            return true;
        }
    }
    false
}
