//! The joint fixed-base table, one affine point per pair of radix-16 digits of tau s

// Vendored from the solana-ed25519 lanes fork, BSD-3-Clause

use super::edwards_x8::ProjectiveNielsX8;
use super::field_x8::LANES;

/// The table holds one entry per low and high digit pair
pub const JOINT_ENTRIES: usize = 256;

/// Affine cached points `lo B + hi 2^128 B` for every digit pair, limb-major for gathers
#[repr(align(64))]
pub struct JointTable {
    pub y_plus_x: [[u64; JOINT_ENTRIES]; 5],
    pub y_minus_x: [[u64; JOINT_ENTRIES]; 5],
    pub t2d: [[u64; JOINT_ENTRIES]; 5],
}

impl JointTable {
    /// Select the entry for each lane's joint digit, with Z equal to one in every entry
    pub fn select(&self, index: &[u64; LANES]) -> ProjectiveNielsX8 {
        let mut out = ProjectiveNielsX8::IDENTITY;
        for (lane, &entry) in index.iter().enumerate() {
            let entry = entry as usize;
            for i in 0..5 {
                out.Y_plus_X.limbs[i][lane] = self.y_plus_x[i][entry];
                out.Y_minus_X.limbs[i][lane] = self.y_minus_x[i][entry];
                out.T2d.limbs[i][lane] = self.t2d[i][entry];
            }
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use alloc::format;
    use alloc::string::String;
    use alloc::vec::Vec;

    use super::*;
    use crate::backend::lanes::joint_data::JOINT_TABLE_B;
    use crate::backend::serial::u64::field::FieldElement51;
    use crate::constants::ED25519_BASEPOINT_POINT;
    use crate::edwards::EdwardsPoint;
    use crate::traits::Identity;

    /// Canonical limbs of every entry as `(y + x, y - x, 2dxy)`
    fn entries() -> Vec<[[u64; 5]; 3]> {
        let canonical =
            |element: &FieldElement51| FieldElement51::from_bytes(&element.to_bytes()).0;
        let mut low = [EdwardsPoint::identity(); 16];
        let mut high = [EdwardsPoint::identity(); 16];
        let high_base = ED25519_BASEPOINT_POINT.mul_by_pow_2(128);
        for digit in 1..16 {
            low[digit] = low[digit - 1] + ED25519_BASEPOINT_POINT;
            high[digit] = high[digit - 1] + high_base;
        }
        let mut out = Vec::with_capacity(JOINT_ENTRIES);
        for entry in 0..JOINT_ENTRIES {
            let niels = (low[entry & 15] + high[entry >> 4]).as_affine_niels();
            out.push([
                canonical(&niels.y_plus_x),
                canonical(&niels.y_minus_x),
                canonical(&niels.xy2d),
            ]);
        }
        out
    }

    // the generated table matches basepoint multiples computed at run time
    #[test]
    fn generated_entries() {
        for (index, entry) in entries().iter().enumerate() {
            let actual: [[u64; 5]; 3] = [
                core::array::from_fn(|i| JOINT_TABLE_B.y_plus_x[i][index]),
                core::array::from_fn(|i| JOINT_TABLE_B.y_minus_x[i][index]),
                core::array::from_fn(|i| JOINT_TABLE_B.t2d[i][index]),
            ];
            assert_eq!(&actual, entry, "entry {index}");
        }
    }

    // prints the joint table source, run with --ignored --nocapture
    #[test]
    #[ignore]
    fn print_table() {
        let entries = entries();
        std::println!("//! The joint fixed-base table for the Ed25519 basepoint");
        std::println!();
        std::println!("// generated by joint::tests::print_table, do not edit");
        std::println!();
        std::println!("use super::joint::JointTable;");
        std::println!();
        std::println!("#[rustfmt::skip]");
        std::println!("pub static JOINT_TABLE_B: JointTable = JointTable {{");
        for (name, coordinate) in [("y_plus_x", 0), ("y_minus_x", 1), ("t2d", 2)] {
            std::println!("    {name}: [");
            for i in 0..5 {
                std::println!("        [");
                for row in entries.chunks(8) {
                    let mut line = String::from("           ");
                    for entry in row {
                        line.push_str(&format!(" {},", entry[coordinate][i]));
                    }
                    std::println!("{line}");
                }
                std::println!("        ],");
            }
            std::println!("    ],");
        }
        std::println!("}};");
    }
}
